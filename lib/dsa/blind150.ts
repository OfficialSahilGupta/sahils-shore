// ----------------------------------------------------------------------------
// Blind 150 Statistics & Aggregations
// ----------------------------------------------------------------------------

export interface Blind150Stats {
  total: number;
  solvedCount: number;
  easyTotal: number;
  easySolved: number;
  mediumTotal: number;
  mediumSolved: number;
  hardTotal: number;
  hardSolved: number;
  completionRate: number; // 0 to 1
  topicProgress: Record<string, { total: number; solved: number }>;
}

/**
 * Normalizes problem title for fuzzy matching (removes punctuation, lowercase, spaces)
 */
export function normalizeDsaTitle(title: string): string {
  return (title || "")
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");
}

/**
 * Finds user problem that matches a Blind 150 problem
 */
export function findMatchingUserProblem(
  blind: Blind150Problem,
  userProblems: DsaProblem[]
): DsaProblem | undefined {
  const normBlind = normalizeDsaTitle(blind.title);
  return userProblems.find((up) => {
    // 1. Check title match
    if (normalizeDsaTitle(up.title) === normBlind) return true;
    // 2. Check link match
    if (
      up.link &&
      blind.link &&
      up.link.toLowerCase().includes(blind.title.toLowerCase().replace(/\s+/g, "-"))
    ) {
      return true;
    }
    return false;
  });
}

/**
 * Calculates user's progress through the Blind 150 syllabus
 */
export function calculateBlind150Stats(userProblems: DsaProblem[]): Blind150Stats {
  let easyTotal = 0;
  let easySolved = 0;
  let mediumTotal = 0;
  let mediumSolved = 0;
  let hardTotal = 0;
  let hardSolved = 0;
  let solvedCount = 0;

  const topicProgress: Record<string, { total: number; solved: number }> = {};

  BLIND_150_LIST.forEach((b) => {
    // Tally totals
    if (b.difficulty === "Easy") easyTotal++;
    else if (b.difficulty === "Medium") mediumTotal++;
    else if (b.difficulty === "Hard") hardTotal++;

    if (!topicProgress[b.topic]) {
      topicProgress[b.topic] = { total: 0, solved: 0 };
    }
    topicProgress[b.topic].total++;

    // Check user solved status
    const match = findMatchingUserProblem(b, userProblems);
    const isSolved =
      match &&
      ((match.status || "").toLowerCase() === "solved" ||
        (match.status || "").toLowerCase() === "mastered");

    if (isSolved) {
      solvedCount++;
      topicProgress[b.topic].solved++;
      if (b.difficulty === "Easy") easySolved++;
      else if (b.difficulty === "Medium") mediumSolved++;
      else if (b.difficulty === "Hard") hardSolved++;
    }
  });

  return {
    total: BLIND_150_LIST.length,
    solvedCount,
    easyTotal,
    easySolved,
    mediumTotal,
    mediumSolved,
    hardTotal,
    hardSolved,
    completionRate:
      BLIND_150_LIST.length > 0 ? solvedCount / BLIND_150_LIST.length : 0,
    topicProgress,
  };
}
